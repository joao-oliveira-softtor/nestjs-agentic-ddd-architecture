export interface ApplyOptions {
  /** A directory holding the files of a bundle, `bundle.json` included. */
  readonly bundleDir: string;
  /** The root of the target git repository (the one with `agentic.config.ts`). */
  readonly projectRoot: string;
  /**
   * The caller listed the files, compared the bundle hash with the sender and confirmed (`--yes`).
   * Without it nothing is written and `apply.confirmation-required` carries the list.
   */
  readonly yes?: boolean;
  /** TEST-ONLY: replaces the CLI entry that runs `compile`. */
  readonly cliEntry?: string;
  /** TEST-ONLY: the compile time limit in ms (default 120 s). */
  readonly timeoutMs?: number;
  /** TEST-ONLY: called before each file is moved into place; a throw simulates a failed write. */
  readonly beforeMove?: (index: number) => void;
  /** TEST-ONLY: replaces `process.exit`, called with 130 after a signal was rolled back. */
  readonly exit?: (code: number) => void;
}

export interface ApplyResult {
  /** `NNNN-slug` of the change directory written. */
  readonly change: string;
  /** Project-relative paths written (compile outputs not included). */
  readonly written: readonly string[];
}

const CONFIG = 'agentic.config.ts';
const DERIVED = new Set(['bundle.json', 'BUNDLE.md']);
const SKELETON = 'target/skeleton/';
const CHANGES = 'target/changes/';
const CHANGE_DIR = /^\d{4}-[a-z0-9]+(-[a-z0-9]+)*$/;
const FORBIDDEN_SEGMENTS = new Set(['.git', '.github', 'node_modules', '.tmp']);
const LOCK = '.tmp/apply.lock';
const INTEGRITY_ONLY =
  'Integrity check only: the hash proves the bundle is unchanged, not who made it. Compare the hash with the sender before passing --yes.';
const RESTORED =
  "the bundle's files were restored, but the files regenerated by compile were not; run `bun run agentic compile` to regenerate them from the restored sources";

/**
 * Why a project-relative, forward-slash write path is refused, or `undefined` when it may be
 * written: it must sit under one of the `allowed` directories (module paths and the change
 * directory) and never inside `.git`, `.github`, `node_modules` or `.tmp` (compared without case
 * and without the trailing dots and spaces Windows ignores).
 */
export function forbiddenWrite(
  rel: string,
  allowed: readonly string[],
): 'apply.path-escape' | 'apply.path-forbidden' | undefined {
  const segments = rel.split('/');
  if (
    rel === '' ||
    rel.includes('\\') ||
    isAbsolute(rel) ||
    /^[A-Za-z]:/.test(rel) ||
    segments.includes('..')
  )
    return 'apply.path-escape';
  const hidden = segments.some((s) =>
    FORBIDDEN_SEGMENTS.has(s.replace(/[. ]+$/, '').toLowerCase()),
  );
  const under = allowed.some((dir) => rel.startsWith(`${dir}/`));
  return hidden || !under ? 'apply.path-forbidden' : undefined;
}

const isInside = (base: string, path: string): boolean => {
  const back = relative(base, path);
  return (
    back !== '' &&
    back !== '..' &&
    !back.startsWith(`..${sep}`) &&
    !isAbsolute(back)
  );
};

/** `path` with its deepest existing ancestor resolved through links (the rest is not yet there). */
async function resolveReal(path: string): Promise<string> {
  const rest: string[] = [];
  for (let cur = path; ; cur = dirname(cur)) {
    try {
      return join(await realpath(cur), ...rest.reverse());
    } catch {
      if (dirname(cur) === cur) return path;
      rest.push(basename(cur));
    }
  }
}

async function exec(cwd: string, cmd: readonly string[]) {
  const child = Bun.spawn([...cmd], { cwd, stdout: 'pipe', stderr: 'pipe' });
  const [stdout, stderr, code] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ]);
  return { stdout, stderr, code };
}

const git = (cwd: string, ...args: string[]) => exec(cwd, ['git', ...args]);

const text = (path: string): Promise<string | null> =>
  readFile(path, 'utf8')
    .then(toLf)
    .catch(() => null);

async function readBundle(dir: string): Promise<{
  manifest: BundleManifest;
  files: Map<string, string>;
}> {
  const mismatch = (why: string) =>
    new AgenticError('apply.hash-mismatch', `the bundle is not intact: ${why}`);
  const manifestText = await text(join(dir, 'bundle.json'));
  if (manifestText === null) throw mismatch('bundle.json is missing');
  const files = new Map<string, string>();
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  for (const e of entries) {
    if (!e.isFile()) continue;
    const rel = toPosix(relative(dir, join(e.parentPath, e.name)));
    if (!DERIVED.has(rel))
      files.set(rel, toLf(await readFile(join(e.parentPath, e.name), 'utf8')));
  }
  let manifest: BundleManifest;
  let rebuilt: BundleManifest;
  try {
    manifest = JSON.parse(manifestText) as BundleManifest;
    const { files: _files, hash: _hash, version: _version, ...rest } = manifest;
    rebuilt = buildManifest(
      rest,
      [...files].map(([path, content]) => ({ path, content })),
    );
  } catch {
    throw mismatch('bundle.json is not a manifest');
  }
  const listed = new Map(manifest.files.map((f) => [f.path, f.sha256]));
  const offending =
    [...files.keys()].find((p) => !listed.has(p)) ??
    [...listed.keys()].find((p) => !files.has(p)) ??
    rebuilt.files.find((f) => listed.get(f.path) !== f.sha256)?.path;
  if (offending !== undefined)
    throw mismatch(`${quote(offending)} differs from the manifest`);
  if (rebuilt.hash !== manifest.hash)
    throw mismatch('the manifest does not match its hash');
  return { manifest, files };
}

interface Planned {
  /** Project-relative, forward slashes. */
  readonly rel: string;
  readonly content: string;
}

/** Skeleton files, the change directory and its `examples.json`, as project-relative writes. */
function plan(
  manifest: BundleManifest,
  files: Map<string, string>,
  changesRel: string,
): { planned: Planned[]; change: string } {
  const planned: Planned[] = [];
  const changes = new Set<string>();
  for (const [path, content] of [...files].sort(([a], [b]) =>
    a < b ? -1 : 1,
  )) {
    if (path.startsWith(SKELETON))
      planned.push({ rel: path.slice(SKELETON.length), content });
    else if (path.startsWith(CHANGES)) {
      const sub = path.slice(CHANGES.length);
      changes.add(sub.split('/')[0]!);
      planned.push({ rel: `${changesRel}/${sub}`, content });
    }
  }
  const [change] = [...changes];
  if (changes.size !== 1 || !CHANGE_DIR.test(change!))
    throw new AgenticError(
      'apply.change-invalid',
      `the bundle must carry exactly one change directory named NNNN-slug, found ${quote([...changes].join(', '))}`,
    );
  planned.push({
    rel: `${changesRel}/${change}/examples.json`,
    content: toLf(stableStringify(manifest.examples)),
  });
  return { planned, change: change! };
}

async function checkBase(
  root: string,
  manifest: BundleManifest,
  lockRel: string,
  planned: readonly Planned[],
): Promise<void> {
  const mismatch = (why: string) =>
    new AgenticError('apply.base-mismatch', why);
  const ref = manifest.baseRef;
  const known =
    !ref.startsWith('-') &&
    (await git(root, 'rev-parse', '--verify', '--quiet', `${ref}^{commit}`))
      .code === 0;
  if (!known)
    throw mismatch(`base ref ${quote(ref)} is not a commit of this repository`);
  // `./` makes the path relative to the project folder, which is below the git root in a monorepo.
  const lock = await git(root, 'show', `HEAD:./${lockRel}`);
  if (lock.code !== 0 || sha256(toLf(lock.stdout)) !== manifest.baseLockHash)
    throw mismatch(
      `the committed ${lockRel} at HEAD is not the lock the bundle was compiled against`,
    );
  for (const { rel } of planned) {
    const base = await git(root, 'show', `${ref}:./${rel}`);
    const atBase = base.code === 0 ? toLf(base.stdout) : null;
    if ((await text(join(root, rel))) !== atBase)
      throw mismatch(
        `${quote(rel)} differs from its content at the base ref (the bundle would overwrite local work)`,
      );
  }
}

/**
 * Moves staged files into place, keeping a backup of every original. `rollback` puts back every
 * original and removes the rest; it runs once (later calls find nothing to undo), so a failed
 * move, a failed compile and a signal can all call it. An aborted `signal` stops the moves.
 */
function transaction(stage: string, root: string, signal: AbortSignal) {
  const done: { abs: string; backup?: string }[] = [];
  const dirs: string[] = [];
  const rollback = async () => {
    for (const { abs, backup } of done.splice(0).reverse()) {
      await rm(abs, { force: true });
      if (backup) await rename(backup, abs);
    }
    for (const dir of dirs.splice(0).reverse())
      await rm(dir, { recursive: true, force: true });
  };
  const move = async (
    planned: readonly Planned[],
    beforeMove?: (index: number) => void,
  ) => {
    try {
      for (const [i, { rel }] of planned.entries()) {
        beforeMove?.(i);
        if (signal.aborted) throw new Error('interrupted by a signal');
        const abs = join(root, rel);
        const created = await mkdir(dirname(abs), { recursive: true });
        if (created) dirs.push(created);
        const original = await readFile(abs).then(
          () => true,
          () => false,
        );
        let backup: string | undefined;
        if (original) {
          backup = join(stage, 'backup', rel);
          await mkdir(dirname(backup), { recursive: true });
          await rename(abs, backup);
        }
        done.push({ abs, backup });
        await rename(join(stage, 'new', rel), abs);
      }
    } catch (error) {
      await rollback();
      throw new AgenticError(
        'apply.write-failed',
        `could not write the bundle, nothing was changed: ${(error as Error).message}`,
      );
    }
  };
  return { move, rollback };
}

/** Every planned path must resolve, through existing links, inside the repo and its allowed root. */
async function checkLinks(
  root: string,
  planned: readonly Planned[],
  allowed: readonly string[],
): Promise<void> {
  const realRoot = await realpath(root);
  const roots = new Map<string, string>();
  for (const { rel } of planned) {
    const dir = allowed.find((a) => rel.startsWith(`${a}/`))!;
    if (!roots.has(dir)) roots.set(dir, await resolveReal(join(root, dir)));
    const real = await resolveReal(join(root, rel));
    if (!isInside(realRoot, real) || !isInside(roots.get(dir)!, real))
      throw new AgenticError(
        'apply.path-forbidden',
        `bundle path ${quote(rel)} resolves through a link outside ${quote(dir)}`,
      );
  }
}

/** Takes `.tmp/apply.lock` exclusively; the returned path is removed by whoever took it. */
async function takeLock(root: string): Promise<string> {
  const path = join(root, LOCK);
  await mkdir(dirname(path), { recursive: true });
  // shortcut: no stale-lock detection, upgrade if crashes leave locks behind
  await writeFile(path, `${process.pid}\n`, { flag: 'wx' }).catch((error) => {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
    throw new AgenticError(
      'apply.locked',
      `another apply holds ${quote(LOCK)}; if no apply is running, delete that file and run again`,
    );
  });
  return path;
}

/** What `apply` would write, for the caller to confirm: new or overwritten, the hash, the caveat. */
async function confirmation(
  root: string,
  manifest: BundleManifest,
  planned: readonly Planned[],
): Promise<AgenticError> {
  const lines: string[] = [];
  for (const { rel } of planned)
    lines.push(
      `  ${(await text(join(root, rel))) === null ? 'new' : 'overwrite'} ${rel}`,
    );
  return new AgenticError(
    'apply.confirmation-required',
    [
      `this would write ${planned.length} file(s) into ${quote(root)}, then run compile; nothing was written:`,
      ...lines,
      `bundle hash: ${manifest.hash}`,
      INTEGRITY_ONLY,
      'Run again with --yes to write them.',
    ].join('\n'),
  );
}

/** Stages the files, moves them into place, runs `compile` on the project; any failure restores them. */
async function writeAndCompile(
  root: string,
  planned: readonly Planned[],
  options: ApplyOptions,
  signal: AbortSignal,
): Promise<void> {
  const stage = await mkdtemp(join(root, '.tmp', 'apply-'));
  try {
    for (const { rel, content } of planned) {
      await mkdir(dirname(join(stage, 'new', rel)), { recursive: true });
      await Bun.write(join(stage, 'new', rel), content);
    }
    const tx = transaction(stage, root, signal);
    await tx.move(planned, options.beforeMove);
    const limit = options.timeoutMs ?? DEFAULT_TIMEOUT_MS;
    const compiled = await run(
      [
        process.execPath,
        '--no-install',
        options.cliEntry ?? defaultCliEntry(),
        'compile',
        '--config',
        CONFIG,
      ],
      root,
      { timeoutMs: limit, env: minimalEnv(), signal },
    );
    if (compiled.timedOut || compiled.code !== 0 || signal.aborted) {
      await tx.rollback();
      throw compiled.timedOut
        ? new AgenticError(
            'apply.compile-timeout',
            `compile did not finish within ${limit / 1000} s and was stopped; ${RESTORED}`,
          )
        : new AgenticError(
            'apply.compile-failed',
            `compile ${signal.aborted ? 'was interrupted by a signal' : 'failed'} after writing the bundle; ${RESTORED}: ${quote(compiled.stderr.trim(), 2000)}`,
          );
    }
  } finally {
    await rm(stage, { recursive: true, force: true });
  }
}

/**
 * Applies a bundle written by `compileBundle` to the project at its base. The bundle is untrusted:
 * the hash proves it is unchanged, not who made it. It verifies the content hash, writes only under
 * a module path and its one `NNNN-slug` change directory (never `.git`, `.github`, `node_modules`,
 * `.tmp`, a root file or through a link out of them), checks the base (committed lock, base ref,
 * untouched target files), and without `yes` stops with the list of files. Under an exclusive lock
 * it stages every write under `<project>/.tmp`, moves it into place all-or-nothing, then runs
 * `compile` (minimal environment, time limit). A failure or a SIGINT/SIGTERM puts every file back.
 */
export async function applyBundle(options: ApplyOptions): Promise<ApplyResult> {
  const root = resolve(options.projectRoot);
  const { manifest, files } = await readBundle(options.bundleDir);
  const config = await loadConfig(join(root, CONFIG));
  const rel = (abs: string) => toPosix(relative(root, abs));
  const changesAbs = join(config.outRoot, config.changesDir);
  const { planned, change } = plan(manifest, files, rel(changesAbs));
  const allowed = [
    ...config.modules.map((m) => rel(resolve(config.root, m.path))),
    `${rel(changesAbs)}/${change}`,
  ];
  for (const { rel: p } of planned) {
    const refusal = forbiddenWrite(p, allowed);
    if (refusal !== undefined)
      throw new AgenticError(
        refusal,
        `bundle path ${quote(p)} is ${refusal === 'apply.path-escape' ? 'outside the project' : 'not under a module path or the change directory, or is inside a protected folder'}`,
      );
  }
  await checkLinks(root, planned, allowed);
  const existing = (await readdir(changesAbs).catch(() => [])).find(
    (n) => n === change.slice(0, 4) || n.startsWith(`${change.slice(0, 4)}-`),
  );
  if (existing !== undefined)
    throw new AgenticError(
      'apply.change-exists',
      `change ${change.slice(0, 4)} already exists as ${quote(`${rel(changesAbs)}/${existing}`)}`,
    );

  const lock = await takeLock(root);
  const abort = new AbortController();
  const work = (async () => {
    try {
      await checkBase(
        root,
        manifest,
        rel(join(config.outRoot, config.out.lock)),
        planned,
      );
      if (!options.yes) throw await confirmation(root, manifest, planned);
      await writeAndCompile(root, planned, options, abort.signal);
    } finally {
      await rm(lock, { force: true });
    }
  })();
  const exit = options.exit ?? ((code: number) => process.exit(code));
  const onSignal = () => {
    abort.abort();
    const done = () => exit(130);
    void work.then(done, done);
  };
  process.on('SIGINT', onSignal);
  process.on('SIGTERM', onSignal);
  try {
    await work;
  } finally {
    process.off('SIGINT', onSignal);
    process.off('SIGTERM', onSignal);
  }
  return { change, written: planned.map((p) => p.rel) };
}
