import { randomUUID } from 'node:crypto';
import {
  lstat,
  mkdir,
  readFile,
  readdir,
  readlink,
  realpath,
  rename,
  rm,
  symlink,
  writeFile,
} from 'node:fs/promises';
import type { Stats } from 'node:fs';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { toLf } from './canonical';
import type { ResolvedConfig } from './config';
import { toPosix, type Coded } from './ir';
import { BLOCK_BEGIN, BLOCK_END } from './render/agents-md';
import type { Rendered } from './render/index';

export type DriftReason =
  'missing' | 'changed' | 'extra' | 'mirror' | 'conflict';

export interface Drift {
  readonly path: string;
  readonly reason: DriftReason;
}

export const driftProblem = (d: Drift): Coded => ({
  code: 'write.outdated',
  message: `outdated (${d.reason}): ${d.path}`,
});

export interface WriteResult {
  readonly written: string[];
  readonly warnings: string[];
}

export const GENERATED_MARK = 'agentic-ddd.generated: "true"';
export const CLAUDE_MD_CONTENT = '@AGENTS.md\n';

export async function writeFileAtomic(
  path: string,
  content: string,
): Promise<void> {
  const target = await linkTarget(path);
  const temporary = join(
    dirname(target),
    `.${basename(target)}.${randomUUID()}.tmp`,
  );
  try {
    await writeFile(temporary, content);
    try {
      await rename(temporary, target);
    } catch (error) {
      if (!RENAME_REFUSED.has((error as NodeJS.ErrnoException).code ?? ''))
        throw error;
      // shortcut: falls back to an in-place write when the rename is refused (file held open on Windows); upgrade to a retry if truncated files are ever reported
      await writeFile(target, content);
    }
  } finally {
    await rm(temporary, { force: true });
  }
}

const RENAME_REFUSED = new Set(['EPERM', 'EBUSY', 'EACCES']);

// A symbolic link is written through (even a dangling one), so the user's link is not replaced by a file.
async function linkTarget(path: string): Promise<string> {
  try {
    return await realpath(path);
  } catch {
    const stat = await lstatOrNull(path);
    return stat?.isSymbolicLink()
      ? resolve(dirname(path), await readlink(path))
      : path;
  }
}

const ABSENT = new Set(['ENOENT', 'ENOTDIR']);

// Only "does not exist" is null: an unreadable file (EISDIR, EACCES) must not look absent.
async function readOrNull(path: string): Promise<string | null> {
  try {
    return await readFile(path, 'utf8');
  } catch (error) {
    if (ABSENT.has((error as NodeJS.ErrnoException).code ?? '')) return null;
    // Bun's message does not name the file.
    throw new Error(`cannot read ${path}: ${(error as Error).message}`, {
      cause: error,
    });
  }
}

// Probing a skill directory: an unreadable SKILL.md means "not generated by us".
const readSkillOrNull = (dir: string): Promise<string | null> =>
  readOrNull(join(dir, 'SKILL.md')).catch(() => null);

async function lstatOrNull(path: string): Promise<Stats | null> {
  try {
    return await lstat(path);
  } catch {
    return null;
  }
}

function locateAgentsBlock(
  text: string,
): { start: number; end: number } | null {
  let offset = 0;
  let begin: number | null = null;
  let end: number | null = null;
  for (const line of text.split('\n')) {
    const marker = line.trim();
    if (marker === BLOCK_BEGIN) {
      begin = offset + (line.length - line.trimStart().length);
      end = null;
    } else if (marker === BLOCK_END && begin !== null && end === null) {
      end = offset + line.trimEnd().length;
    }
    offset += line.length + 1;
  }
  return begin === null || end === null ? null : { start: begin, end };
}

export function extractAgentsBlock(text: string): string | null {
  const located = locateAgentsBlock(text);
  return located === null ? null : text.slice(located.start, located.end);
}

export function mergeAgentsBlock(
  existing: string | null,
  block: string,
): string {
  if (existing === null) return `# AGENTS.md\n\n${block}\n`;
  const located = locateAgentsBlock(existing);
  if (located === null) return `${existing.trimEnd()}\n\n${block}\n`;
  return `${existing.slice(0, located.start)}${block}${existing.slice(located.end)}`;
}

function isGenerated(skill: string | null): boolean {
  if (skill === null) return false;
  const lines = skill.split('\n');
  if (lines[0]?.trim() !== '---') return false;
  const close = lines.findIndex((line, i) => i > 0 && line.trim() === '---');
  return (
    close !== -1 &&
    lines.slice(1, close).some((line) => line.includes(GENERATED_MARK))
  );
}

async function generatedSkillDirs(base: string): Promise<string[]> {
  let names: string[];
  try {
    names = await readdir(base);
  } catch {
    return [];
  }
  const result: string[] = [];
  for (const name of names.sort()) {
    if (isGenerated(await readSkillOrNull(join(base, name))))
      result.push(name);
  }
  return result;
}

// The directory itself or anything inside it is a link; hard links are out of scope. Bun's recursive readdir lists a linked directory without descending into it.
async function containsLink(dir: string): Promise<boolean> {
  if ((await lstat(dir)).isSymbolicLink()) return true;
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  return entries.some((entry) => entry.isSymbolicLink());
}

// Nothing is deleted before the new files are written, so a failure in between keeps the old skills:
// kept directories are overwritten in place and orphans go away after the writes.
async function planSkillDirs(
  config: ResolvedConfig,
  rendered: Rendered,
): Promise<{ keptDirs: [string, string][]; orphans: string[] }> {
  const keptDirs: [string, string][] = [];
  const orphans: string[] = [];
  for (const [base, keep] of managedBases(config, rendered)) {
    for (const dir of await generatedSkillDirs(join(config.outRoot, base))) {
      const absolute = join(config.outRoot, base, dir);
      if (!keep.includes(dir)) orphans.push(`${base}/${dir}`);
      // rm removes a link without following it, so nothing is written or pruned through one
      else if (await containsLink(absolute))
        await rm(absolute, { recursive: true, force: true });
      else keptDirs.push([base, dir]);
    }
  }
  return { keptDirs, orphans };
}

async function conflictingDirs(
  config: ResolvedConfig,
  rendered: Rendered,
): Promise<Set<string>> {
  const conflicts = new Set<string>();
  for (const [base, keep] of managedBases(config, rendered)) {
    for (const dir of keep) {
      const absolute = join(config.outRoot, base, dir);
      if ((await lstatOrNull(absolute)) === null) continue;
      if (!isGenerated(await readSkillOrNull(absolute)))
        conflicts.add(`${base}/${dir}`);
    }
  }
  return conflicts;
}

function inConflict(conflicts: ReadonlySet<string>, path: string): boolean {
  for (const dir of conflicts) if (path.startsWith(`${dir}/`)) return true;
  return false;
}

async function listFiles(dir: string): Promise<string[]> {
  const files: string[] = [];
  for await (const file of new Bun.Glob('**/*').scan({
    cwd: dir,
    onlyFiles: true,
    dot: true,
  }))
    files.push(toPosix(file));
  return files.sort();
}

// The one rule for "a file the generator no longer owns", shared by write and check.
async function extraFiles(
  config: ResolvedConfig,
  rendered: Rendered,
  base: string,
  dir: string,
): Promise<string[]> {
  const files = await listFiles(join(config.outRoot, base, dir));
  return files
    .map((file) => `${base}/${dir}/${file}`)
    .filter((path) => !rendered.files.has(path));
}

function managedBases(
  config: ResolvedConfig,
  rendered: Rendered,
): [string, readonly string[]][] {
  return [
    [config.out.devSkills, rendered.devSkillDirs],
    [config.out.runtimeSkills, rendered.runtimeSkillDirs],
  ];
}

function skillsRootOf(config: ResolvedConfig): string {
  return `${resolve(config.outRoot, config.out.devSkills)}${sep}`;
}

// Same condition for writing (removes the link) and for check (reports the link).
async function isDanglingSkillTarget(
  target: string,
  skillsRoot: string,
): Promise<boolean> {
  return target.startsWith(skillsRoot) && (await lstatOrNull(target)) === null;
}

function mirrorTarget(
  config: ResolvedConfig,
  mirror: string,
  dir: string,
): string {
  return toPosix(
    relative(
      join(config.outRoot, mirror),
      join(config.outRoot, config.out.devSkills, dir),
    ),
  );
}

export async function writeOutputs(
  config: ResolvedConfig,
  rendered: Rendered,
): Promise<WriteResult> {
  const written: string[] = [];
  const warnings: string[] = [];
  // Read the user's files first: if one cannot be read, nothing has been written yet.
  const agentsPath = join(config.outRoot, config.out.agentsMd);
  const claudePath = join(config.outRoot, config.out.claudeMd);
  const existingAgents = await readOrNull(agentsPath);
  await readOrNull(claudePath);
  const conflicts = await conflictingDirs(config, rendered);
  for (const dir of [...conflicts].sort()) {
    warnings.push(
      `${dir} exists and was not generated by agentic-ddd; it was not overwritten`,
    );
  }

  const { keptDirs, orphans } = await planSkillDirs(config, rendered);
  const removedOrphans = new Set(
    orphans.map((dir) => resolve(config.outRoot, dir)),
  );
  written.push(...orphans.map((dir) => `${dir} (removed)`));

  for (const [path, content] of rendered.files) {
    if (inConflict(conflicts, path)) continue;
    const absolute = join(config.outRoot, path);
    await mkdir(dirname(absolute), { recursive: true });
    await writeFile(absolute, content);
    written.push(path);
  }

  for (const [base, dir] of keptDirs) {
    for (const path of await extraFiles(config, rendered, base, dir))
      await rm(join(config.outRoot, path), { force: true });
  }
  for (const absolute of removedOrphans)
    await rm(absolute, { recursive: true, force: true });

  await mkdir(dirname(agentsPath), { recursive: true });
  await writeFileAtomic(
    agentsPath,
    mergeAgentsBlock(existingAgents, rendered.agentsBlock),
  );
  written.push(config.out.agentsMd);

  // Decided only now: CLAUDE.md may be a link to the AGENTS.md just written, or its target.
  if ((await readOrNull(claudePath)) === null) {
    await mkdir(dirname(claudePath), { recursive: true });
    await writeFile(claudePath, CLAUDE_MD_CONTENT);
    written.push(config.out.claudeMd);
  }

  const skillsRoot = skillsRootOf(config);
  for (const mirror of config.mirrors) {
    const mirrorDir = join(config.outRoot, mirror);
    await mkdir(mirrorDir, { recursive: true });
    for (const name of (await readdir(mirrorDir)).sort()) {
      const link = join(mirrorDir, name);
      const stat = await lstat(link);
      if (!stat.isSymbolicLink() || rendered.devSkillDirs.includes(name))
        continue;
      const target = resolve(mirrorDir, await readlink(link));
      const dangling = await isDanglingSkillTarget(target, skillsRoot);
      if (dangling || removedOrphans.has(target)) {
        await rm(link, { force: true });
        written.push(`${mirror}/${name} (link removed)`);
      }
    }
    for (const dir of rendered.devSkillDirs) {
      if (conflicts.has(`${config.out.devSkills}/${dir}`)) continue;
      const link = join(mirrorDir, dir);
      const stat = await lstatOrNull(link);
      if (stat && !stat.isSymbolicLink()) {
        warnings.push(
          `${mirror}/${dir} exists and is not a link; it was not replaced`,
        );
        continue;
      }
      if (stat) await rm(link, { force: true });
      await symlink(mirrorTarget(config, mirror, dir), link);
      written.push(`${mirror}/${dir}`);
    }
  }

  return { written, warnings };
}

export async function checkOutputs(
  config: ResolvedConfig,
  rendered: Rendered,
): Promise<Drift[]> {
  const drift: Drift[] = [];
  const conflicts = await conflictingDirs(config, rendered);
  for (const dir of conflicts) drift.push({ path: dir, reason: 'conflict' });

  for (const [path, content] of rendered.files) {
    if (inConflict(conflicts, path)) continue;
    // Unreadable (a directory, EACCES) counts as missing here; only AGENTS.md and CLAUDE.md are strict.
    const actual = await readOrNull(join(config.outRoot, path)).catch(
      () => null,
    );
    if (actual === null) drift.push({ path, reason: 'missing' });
    // A checkout with CRLF is not drift: only the text read from disk is normalized.
    else if (toLf(actual) !== content) drift.push({ path, reason: 'changed' });
  }

  for (const [base, keep] of managedBases(config, rendered)) {
    for (const dir of await generatedSkillDirs(join(config.outRoot, base))) {
      if (!keep.includes(dir)) {
        drift.push({ path: `${base}/${dir}`, reason: 'extra' });
        continue;
      }
      for (const path of await extraFiles(config, rendered, base, dir))
        drift.push({ path, reason: 'extra' });
    }
  }

  const agents = await readOrNull(join(config.outRoot, config.out.agentsMd));
  const block = agents === null ? null : extractAgentsBlock(agents);
  if (block === null)
    drift.push({ path: config.out.agentsMd, reason: 'missing' });
  else if (toLf(block) !== rendered.agentsBlock)
    drift.push({ path: config.out.agentsMd, reason: 'changed' });

  if ((await readOrNull(join(config.outRoot, config.out.claudeMd))) === null) {
    drift.push({ path: config.out.claudeMd, reason: 'missing' });
  }

  const skillsRoot = skillsRootOf(config);
  for (const mirror of config.mirrors) {
    const mirrorDir = join(config.outRoot, mirror);
    const names = await readdir(mirrorDir).catch(() => [] as string[]);
    for (const name of names.sort()) {
      if (rendered.devSkillDirs.includes(name)) continue;
      const link = join(mirrorDir, name);
      if (!(await lstat(link)).isSymbolicLink()) continue;
      const target = resolve(mirrorDir, await readlink(link));
      if (await isDanglingSkillTarget(target, skillsRoot))
        drift.push({ path: `${mirror}/${name}`, reason: 'extra' });
    }
    for (const dir of rendered.devSkillDirs) {
      if (conflicts.has(`${config.out.devSkills}/${dir}`)) continue;
      const link = join(config.outRoot, mirror, dir);
      const stat = await lstatOrNull(link);
      if (stat && !stat.isSymbolicLink()) {
        drift.push({ path: `${mirror}/${dir}`, reason: 'conflict' });
      } else if (
        !stat ||
        // No Windows o readlink devolve o alvo com `\`.
        toPosix(await readlink(link)) !== mirrorTarget(config, mirror, dir)
      ) {
        drift.push({ path: `${mirror}/${dir}`, reason: 'mirror' });
      }
    }
  }

  return drift.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}
